#!/usr/bin/env python
"""The SDK generator (doc 15 §6) — T3.25.

**Generated, not hand-written, and that is the invariant rather than a
convenience.** Doc 15 §6: keeping the SDK generated from doc 12's contract "is
what guarantees the SDK never drifts from the two front doors … it enforces
invariant 17 (the SDK cannot expose a behaviour the contract does not)". So the
generator reads the *live* OpenAPI document off the running app object — the
same schema the app serves — rather than a checked-in copy that could age.

**Three verbs, deliberately** — `capture`, `search`, `declareContext`. darkmem
is not building a client platform; doc 00 §8's success criterion is that a
minimal SDK exists. Each verb is bound to a route that must exist in the
contract, and generation **fails** if one does not: an SDK method with no route
behind it is precisely the drift this design exists to prevent.

**Output is deterministic.** No timestamps, no versions read from the
environment, sorted everywhere — because ``make generate && git diff
--exit-code`` is the task's own verification, and a generator whose output
moves on every run cannot be checked that way. The contract hash *is* recorded,
since a regeneration that changes nothing but the hash is exactly the signal a
reader wants when the contract moved.

Run from ``sdks/``::

    make generate
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

SDKS = Path(__file__).resolve().parent
sys.path.insert(0, str(SDKS.parent / "backend"))

# The three verbs, each pinned to the contract route it wraps. The pinning is
# the point: if a route is renamed, generation fails here rather than emitting
# an SDK that calls a 404.
VERBS = {
    "capture": {"method": "post", "path": "/api/v1/memories"},
    "search": {"method": "post", "path": "/api/v1/memories/search"},
    "declareContext": {"method": "post", "path": "/api/v1/memories/reason"},
}


def contract() -> dict:
    from app.main import app  # imported late: it pulls the whole application in

    return app.openapi()


def _require_routes(schema: dict) -> None:
    missing = [
        f"{verb['method'].upper()} {verb['path']}"
        for verb in VERBS.values()
        if verb["method"] not in schema["paths"].get(verb["path"], {})
    ]
    if missing:
        raise SystemExit(
            "refusing to generate: the contract has no route for "
            + ", ".join(missing)
            + ". An SDK method with no route behind it is the drift doc 15 §6 "
            "generates the SDK to prevent."
        )


def _hash(schema: dict) -> str:
    """A stable digest of the routes the SDK actually binds to.

    Not of the whole document: the SDK is three verbs, and hashing all 116
    paths would report a change every time an unrelated route moved, training
    a reader to ignore it.
    """
    bound = {
        f"{verb['method']} {verb['path']}": schema["paths"][verb["path"]][verb["method"]]
        for verb in VERBS.values()
    }
    return hashlib.sha256(
        json.dumps(bound, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()[:16]


HEADER = (
    "// Generated by sdks/generate.py from darkmem's OpenAPI contract (doc 12).\n"
    "// Do not edit: run `make generate` in sdks/ instead.\n"
    "// contract: {digest}\n"
)

PY_HEADER = (
    '"""Generated by sdks/generate.py from darkmem\'s OpenAPI contract (doc 12).\n\n'
    "Do not edit: run ``make generate`` in ``sdks/`` instead.\n"
    "contract: {digest}\n"
    '"""\n'
)


def render_typescript(digest: str) -> str:
    return HEADER.format(digest=digest) + '''
export interface DarkmemOptions {
  baseUrl?: string;
  token?: string;
  project?: string;
}

export interface CaptureResult {
  id: string;
}

/** A thin typed wrapper over the two front doors. Three verbs, no framework. */
export class Darkmem {
  private readonly baseUrl: string;
  private readonly token?: string;
  private readonly project?: string;

  constructor(options: DarkmemOptions = {}) {
    this.baseUrl = options.baseUrl ?? "http://localhost:8000";
    this.token = options.token;
    this.project = options.project;
  }

  /** Capture answers 202 with a pre-minted id: every door buffers. */
  async capture(
    content: string,
    options: { project?: string; source?: string; context?: unknown } = {},
  ): Promise<CaptureResult> {
    return this.post("{capture}", {
      content,
      project: options.project ?? this.project,
      source: options.source,
      applies_when: options.context,
    });
  }

  async search(
    query: string,
    options: { project?: string; limit?: number; context?: unknown } = {},
  ): Promise<unknown> {
    return this.post("{search}", {
      query,
      project: options.project ?? this.project,
      limit: options.limit,
      applies_when: options.context,
    });
  }

  /** Declare the session's context once; later calls inherit it. */
  declareContext(context: unknown): void {
    this.context = context;
  }

  private context: unknown = undefined;

  private async post(path: string, body: unknown): Promise<never> {
    const response = await fetch(`${this.baseUrl}${path}`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        ...(this.token ? { Authorization: `Bearer ${this.token}` } : {}),
      },
      body: JSON.stringify(body),
    });
    if (!response.ok) {
      throw new Error(`darkmem ${path} answered ${response.status}`);
    }
    return response.json() as Promise<never>;
  }
}
'''.replace("{capture}", VERBS["capture"]["path"]).replace(
        "{search}", VERBS["search"]["path"]
    )


def render_python(digest: str) -> str:
    return PY_HEADER.format(digest=digest) + f'''
from __future__ import annotations

from typing import Any

import httpx

CAPTURE_PATH = "{VERBS['capture']['path']}"
SEARCH_PATH = "{VERBS['search']['path']}"


class Darkmem:
    """A thin typed wrapper over the two front doors. Three verbs, no framework."""

    def __init__(
        self,
        base_url: str = "http://localhost:8000",
        token: str | None = None,
        project: str | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.token = token
        self.project = project
        self._context: Any = None

    def declare_context(self, context: Any) -> None:
        """Declare the session's context once; later calls inherit it."""
        self._context = context

    async def capture(
        self,
        content: str,
        *,
        project: str | None = None,
        source: str | None = None,
        context: Any = None,
    ) -> dict:
        """Capture answers 202 with a pre-minted id: every door buffers."""
        return await self._post(CAPTURE_PATH, {{
            "content": content,
            "project": project or self.project,
            "source": source,
            "applies_when": context if context is not None else self._context,
        }})

    async def search(
        self,
        query: str,
        *,
        project: str | None = None,
        limit: int | None = None,
        context: Any = None,
    ) -> dict:
        return await self._post(SEARCH_PATH, {{
            "query": query,
            "project": project or self.project,
            "limit": limit,
            "applies_when": context if context is not None else self._context,
        }})

    async def _post(self, path: str, body: dict) -> dict:
        headers = {{"Content-Type": "application/json"}}
        if self.token:
            headers["Authorization"] = f"Bearer {{self.token}}"
        async with httpx.AsyncClient() as client:
            response = await client.post(
                f"{{self.base_url}}{{path}}",
                json={{k: v for k, v in body.items() if v is not None}},
                headers=headers,
            )
            response.raise_for_status()
            return response.json()
'''


def main() -> int:
    schema = contract()
    _require_routes(schema)
    digest = _hash(schema)

    files = {
        SDKS / "ts/src/client.ts": render_typescript(digest),
        SDKS / "python/darkmem_sdk/client.py": render_python(digest),
    }
    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(SDKS)}")

    print(f"contract {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
